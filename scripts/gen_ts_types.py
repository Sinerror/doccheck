"""Generate web/src/types/events.ts from doccheck/events.py so the contract cannot drift.

    uv run python scripts/gen_ts_types.py [--out web/src/types/events.ts]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from doccheck.events import EVENT_DATA_MODELS, Event  # noqa: E402
from doccheck.models import AnalystRevision, AnalystVerdict, Claim, Critique, Summary  # noqa: E402

# Domain payloads carried inside agent.output / scout.claims (typed on the frontend via casts).
DOMAIN_MODELS = (Claim, AnalystVerdict, AnalystRevision, Critique, Summary)


def ts_type(s: dict[str, Any], defs: dict[str, Any]) -> str:
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "const" in s:
        return repr(s["const"]).replace("'", '"')
    if "enum" in s:
        return " | ".join(f'"{v}"' if isinstance(v, str) else str(v).lower() for v in s["enum"])
    if "anyOf" in s:
        return " | ".join(dict.fromkeys(ts_type(x, defs) for x in s["anyOf"]))
    t = s.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(s.get("items", {}), defs)
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        if "properties" in s:
            return "{ " + "; ".join(_props(s, defs)) + " }"
        ap = s.get("additionalProperties")
        return f"Record<string, {ts_type(ap, defs) if isinstance(ap, dict) else 'unknown'}>"
    return "unknown"


def _props(s: dict[str, Any], defs: dict[str, Any]) -> list[str]:
    req = set(s.get("required", []))
    return [f"{k}{'' if k in req else '?'}: {ts_type(v, defs)}" for k, v in s.get("properties", {}).items()]


def interface(name: str, s: dict[str, Any], defs: dict[str, Any]) -> str:
    body = "\n".join(f"  {p};" for p in _props(s, defs))
    return f"export interface {name} {{\n{body}\n}}\n"


def generate() -> str:
    out = ["// AUTO-GENERATED by scripts/gen_ts_types.py from doccheck/events.py — do not edit.\n"]
    env = Event.model_json_schema()
    env_props = [p for p in _props(env, {}) if not p.startswith(("type", "data"))]
    names: dict[str, str] = {}
    emitted: set[str] = set()

    def emit_model(model) -> None:
        schema = model.model_json_schema()
        for dn, ds in schema.get("$defs", {}).items():
            if dn not in emitted:
                emitted.add(dn)
                out.append(interface(dn, ds, {}) if "properties" in ds
                           else f"export type {dn} = {ts_type(ds, {})};\n")
        if model.__name__ not in emitted:
            emitted.add(model.__name__)
            out.append(interface(model.__name__, schema, {}))

    for etype, model in EVENT_DATA_MODELS.items():
        emit_model(model)
        names[etype] = model.__name__
    out.append("// ---- domain payloads ----\n")
    for model in DOMAIN_MODELS:
        emit_model(model)
    out.append("export interface EventDataMap {\n" + "\n".join(f'  "{k}": {v};' for k, v in names.items()) + "\n}\n")
    out.append("export type EventType = keyof EventDataMap;\n")
    out.append("export interface DocCheckEventOf<T extends EventType> {\n" + "\n".join(f"  {p};" for p in env_props)
               + "\n  type: T;\n  data: EventDataMap[T];\n}\n")
    out.append("export type DocCheckEvent = { [K in EventType]: DocCheckEventOf<K> }[EventType];\n")
    out.append("export const EVENT_TYPES: EventType[] = [" + ", ".join(f'"{k}"' for k in names) + "];\n")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "web" / "src" / "types" / "events.ts"))
    args = ap.parse_args()
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(generate(), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
