DOCS = DOCS + HARD_DOCS

EXPECTED = {"not_in_sources": NOT_FOUND, "wrong_clause": NOT_FOUND + ["OVERSTATED"]}


def build() -> dict:
    OUT_DOCS.mkdir(parents=True, exist_ok=True)
    labels = {"docs": []}
    n_err = n_ok = 0
    for d in DOCS:
        body_parts: list[str] = []
        planted, clean = [], []
        for label, text, gold in d["parts"]:
            body_parts.append(text)
            if label is None:
                continue
            item = {"text": text, "gold": [{"file": f, "section": s} for f, s in gold]}
            if label == "ok":
                n_ok += 1
                item["id"] = f"{d['file'][:3]}-ok{len(clean) + 1}"
                clean.append(item)
            else:
                n_err += 1
                item["id"] = f"{d['file'][:3]}-{'ABCDEFGH'[len(planted)]}"
                item["kind"] = label
                item["expected"] = EXPECTED.get(label, STRICT)
                planted.append(item)
        (OUT_DOCS / d["file"]).write_text("\n\n".join(body_parts) + "\n", encoding="utf-8")
        labels["docs"].append({"file": d["file"], "type": d["type"], "title": d["title"],
                               "difficulty": d["difficulty"], "planted": planted, "clean": clean})
    labels["totals"] = {"docs": len(DOCS), "planted": n_err, "clean": n_ok,
                        "hard_docs": sum(d["difficulty"] == "hard" for d in DOCS)}
    OUT_LABELS.write_text(json.dumps(labels, ensure_ascii=False, indent=1), encoding="utf-8")
    return labels


